import tkinter as tk
from tkinter import ttk, messagebox
import math

# Jerarquía de clases
class FiguraGeometrica:
    """Clase base para todas las figuras geométricas."""
    def calcular_volumen(self):
        raise NotImplementedError

    def calcular_superficie(self):
        raise NotImplementedError

class Cilindro(FiguraGeometrica):
    def __init__(self, radio, altura):
        self.radio = radio
        self.altura = altura

    def calcular_volumen(self):
        return math.pi * (self.radio ** 2) * self.altura

    def calcular_superficie(self):
        return 2 * math.pi * self.radio * (self.radio + self.altura)

class Esfera(FiguraGeometrica):
    def __init__(self, radio):
        self.radio = radio

    def calcular_volumen(self):
        return (4/3) * math.pi * (self.radio ** 3)

    def calcular_superficie(self):
        return 4 * math.pi * (self.radio ** 2)

class Piramide(FiguraGeometrica):
    def __init__(self, base, altura, apotema):
        self.base = base
        self.altura = altura
        self.apotema = apotema

    def calcular_volumen(self):
        return (1/3) * (self.base ** 2) * self.altura

    def calcular_superficie(self):
        return (self.base ** 2) + (2 * self.base * self.apotema)

class Cubo(FiguraGeometrica):
    def __init__(self, lado):
        self.lado = lado

    def calcular_volumen(self):
        return self.lado ** 3

    def calcular_superficie(self):
        return 6 * (self.lado ** 2)

class Prisma(FiguraGeometrica):
    def __init__(self, largo, ancho, altura):
        self.largo = largo
        self.ancho = ancho
        self.altura = altura

    def calcular_volumen(self):
        return self.largo * self.ancho * self.altura

    def calcular_superficie(self):
        return 2 * (self.largo * self.ancho + self.largo * self.altura + self.ancho * self.altura)


# Interfaz Gráfica
class CalculadoraFiguras:
    def __init__(self, ventana):
        self.ventana = ventana
        self.ventana.title("Calculadora Geométricas")
        self.ventana.geometry("450x450")

        self.notebook = ttk.Notebook(ventana)
        self.notebook.pack(expand=True, fill='both', padx=10, pady=10)

        self.config_figuras = {
            "Cilindro": {"clase": Cilindro, "campos": ["Radio (cm):", "Altura (cm):"], "img": "cilindro.png"},
            "Esfera": {"clase": Esfera, "campos": ["Radio (cm):"], "img": "esfera.png"},
            "Pirámide": {"clase": Piramide, "campos": ["Base (cm):", "Altura (cm):", "Apotema (cm):"], "img": "piramide.png"},
            "Cubo": {"clase": Cubo, "campos": ["Lado (cm):"], "img": "cubo.png"},
            "Prisma Rectangular": {"clase": Prisma, "campos": ["Largo (cm):", "Ancho (cm):", "Altura (cm):"], "img": "prisma.png"}
        }

        self.imagenes_cargadas = {}
        self.construir_pestanas()

    def construir_pestanas(self):
        for nombre, datos in self.config_figuras.items():
            frame = ttk.Frame(self.notebook)
            self.notebook.add(frame, text=nombre)

            try:
                img = tk.PhotoImage(file=datos["img"])
                lbl_img = tk.Label(frame, image=img)
                lbl_img.image = img
                self.imagenes_cargadas[nombre] = img
            except tk.TclError:
                lbl_img = tk.Label(frame, text=f"[Imagen de {nombre} no encontrada]\n(Guardar como '{datos['img']}')",
                                   bg="lightgray", width=30, height=5)
            lbl_img.pack(pady=10)

            frame_entradas = tk.Frame(frame)
            frame_entradas.pack(pady=10)

            entradas = []
            for i, campo in enumerate(datos["campos"]):
                tk.Label(frame_entradas, text=campo).grid(row=i, column=0, padx=5, pady=5, sticky="e")
                entry = tk.Entry(frame_entradas)
                entry.grid(row=i, column=1, padx=5, pady=5)
                entradas.append(entry)

            lbl_vol = tk.Label(frame, text="Volumen: - cm³", font=("Arial", 10, "bold"))
            lbl_vol.pack(pady=5)
            lbl_sup = tk.Label(frame, text="Superficie: - cm²", font=("Arial", 10, "bold"))
            lbl_sup.pack(pady=5)

            btn_calcular = tk.Button(frame, text="Calcular",
                                     command=lambda c=datos["clase"], ents=entradas, lv=lbl_vol, ls=lbl_sup:
                                     self.ejecutar_calculo(c, ents, lv, ls))
            btn_calcular.pack(pady=15)

    def ejecutar_calculo(self, clase_figura, entradas, lbl_vol, lbl_sup):
        valores = []
        for entrada in entradas:
            val = entrada.get().strip()
            if not val:
                messagebox.showwarning("Faltan datos", "Debe completar todos los campos.")
                return
            try:
                valores.append(float(val))
            except ValueError:
                messagebox.showerror("Error", "Ingrese únicamente valores numéricos.")
                return

        figura = clase_figura(*valores)
        lbl_vol.config(text=f"Volumen: {figura.calcular_volumen():.2f} cm³")
        lbl_sup.config(text=f"Superficie: {figura.calcular_superficie():.2f} cm²")


if __name__ == "__main__":
    raiz = tk.Tk()
    app = CalculadoraFiguras(raiz)
    raiz.mainloop()