import tkinter as tk
from tkinter import messagebox
import statistics

class Estudiante:
    def __init__(self, notas):
        self.notas = notas

    def calcular_promedio(self):
        return sum(self.notas) / len(self.notas)

    def calcular_desviacion_estandar(self):
        # Se utiliza la desviación estándar poblacional
        return statistics.pstdev(self.notas)

    def obtener_mayor_nota(self):
        return max(self.notas)

    def obtener_menor_nota(self):
        return min(self.notas)

class InterfazNotas:
    def __init__(self, ventana):
        self.ventana = ventana
        self.ventana.title("Cálculo de Notas")
        self.ventana.geometry("320x350")

        self.entradas = []

        for i in range(5):
            tk.Label(self.ventana, text=f"Nota {i+1}:").grid(row=i, column=0, padx=20, pady=5, sticky="w")
            entrada = tk.Entry(self.ventana, width=15)
            entrada.grid(row=i, column=1, padx=20, pady=5)
            self.entradas.append(entrada)

        tk.Button(self.ventana, text="Calcular Resultados", command=self.procesar_notas).grid(row=5, column=0, columnspan=2, pady=15)

        self.lbl_prom = tk.Label(self.ventana, text="Promedio: -")
        self.lbl_prom.grid(row=6, column=0, columnspan=2, sticky="w", padx=20)

        self.lbl_desv = tk.Label(self.ventana, text="Desviación Estándar: -")
        self.lbl_desv.grid(row=7, column=0, columnspan=2, sticky="w", padx=20)

        self.lbl_max = tk.Label(self.ventana, text="Mayor Nota: -")
        self.lbl_max.grid(row=8, column=0, columnspan=2, sticky="w", padx=20)

        self.lbl_min = tk.Label(self.ventana, text="Menor Nota: -")
        self.lbl_min.grid(row=9, column=0, columnspan=2, sticky="w", padx=20)

    def procesar_notas(self):
        valores = [entrada.get().strip() for entrada in self.entradas]

        if "" in valores:
            messagebox.showwarning("Alerta", "Es obligatorio ingresar las cinco notas.")
            return

        notas_numericas = []
        for valor in valores:
            try:
                notas_numericas.append(float(valor))
            except ValueError:
                messagebox.showerror("Error", "Se han ingresado datos que no son numéricos.")
                return

        estudiante = Estudiante(notas_numericas)

        self.lbl_prom.config(text=f"Promedio: {estudiante.calcular_promedio():.2f}")
        self.lbl_desv.config(text=f"Desviación Estándar: {estudiante.calcular_desviacion_estandar():.2f}")
        self.lbl_max.config(text=f"Mayor Nota: {estudiante.obtener_mayor_nota()}")
        self.lbl_min.config(text=f"Menor Nota: {estudiante.obtener_menor_nota()}")

if __name__ == "__main__":
    raiz = tk.Tk()
    app = InterfazNotas(raiz)
    raiz.mainloop()